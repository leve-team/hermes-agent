# ---------------------------------------------------------------------------
# Schema
# ---------------------------------------------------------------------------
#
# Mirrors the SQLite schema in hermes_state.SCHEMA_SQL so the adapter can run the
# same SessionDB queries unchanged.
#
# This literal is NOT the enforcement mechanism for that parity, and must not be
# read as proof of it — it is hand-maintained, and for a long stretch it claimed
# a column-for-column mirror it did not have (four columns and one whole table
# had drifted, silently costing the deployment its session history). The enforcement
# is ``reconcile_postgres_columns``, which diffs this live schema against
# SCHEMA_SQL on every connect and ADDs whatever is missing — the same
# declarative contract hermes_state._reconcile_columns gives SQLite.
#
# Keep declaring new columns here anyway: it is what a fresh database gets in one
# CREATE TABLE, and it documents intent. But a column reaching Postgres no longer
# depends on someone remembering to.
#
# Dialect differences:
#   * INTEGER PRIMARY KEY AUTOINCREMENT  -> BIGINT GENERATED BY DEFAULT AS
#     IDENTITY PRIMARY KEY (server-assigned monotonic id; migration may also
#     supply explicit ids, hence BY DEFAULT not ALWAYS).
#   * REAL                               -> DOUBLE PRECISION
#   * No FTS5 virtual tables (PostgreSQL has no fts5; search uses ILIKE,
#     accelerated by pg_trgm GIN indexes when pg_trgm is installed — see
#     _PG_ONLY_MIGRATIONS / apply_postgres_migrations).
# The integer/boolean flag columns (observed, active, archived, rewind_count)
# stay INTEGER to match how SessionDB writes and filters them (``active = 1``).
#
# PG3 also carries the state.db ledgers whose current owners connect to SQLite
# directly.  Declaring them here makes fresh and already-initialized writable
# PostgreSQL stores converge when this base schema is replayed.  Their writers
# must still move behind SessionDB before a live dual-write window can cover
# new mutations; schema/COPY parity alone cannot observe a bypass writer.

